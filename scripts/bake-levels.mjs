import { writeFileSync } from 'node:fs';
import { VesselLogic as L } from '../src/game-logic.js';
const baked = {};
for (const difficulty of ['relaxed', 'normal', 'expert']) {
  baked[difficulty] = [];
  for (let level = 1; level <= L.MAX_LEVEL; level++) {
    const g = L.generateLevel(level, difficulty);
    const result = L.solve(g.state, 400000, new Set(g.specials.frozen));
    if (!result.solution) throw new Error(`Unsolvable: ${difficulty} ${level}`);
    baked[difficulty].push({ v: L.RULES_VERSION, o: g.seedOffset, p: result.solution.length });
  }
}
writeFileSync(new URL('../src/levels-baked.js', import.meta.url), '// Generated by npm run bake; all classic levels verified before shipping.\nexport const BAKED = ' + JSON.stringify(baked) + ';\n');
